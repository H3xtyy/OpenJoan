"""OpenJoan's own window icon (ADR-0002): drawn here from primitives, nothing taken from the game.

Writes, from the repository root:
  src/runtime/loader/openjoan.ico        icon group with 16, 32 and 48 pixel images (BMP-encoded, as the game's icon loader
                                 and Windows' LoadIconA expect; resource id 102 in src/runtime/loader/joan_re.rc)
  src/platform/openjoan_icon.inc the 32 x 32 image as ARGB words for the SDL window on platforms without PE
                                 resources (platform/sdl_window.cpp)

Artwork: a deep-blue shield with a gold sword (blade, cross guard, pommel) - a plain heraldic motif of our own.
Rendered at 256 px with Pillow's drawing primitives and down-sampled for the small sizes.

  python3 tools/make_icon.py
"""
import os
import sys

try:
    from PIL import Image, ImageDraw
except ImportError:
    sys.exit('make_icon: Pillow is needed (pip install pillow / dnf install python3-pillow)')

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BLUE, BLUE_DARK, GOLD, GOLD_DARK = (30, 58, 138, 255), (17, 36, 92, 255), (212, 160, 23, 255), (160, 115, 10, 255)


def draw(size=256):
    im = Image.new('RGBA', (size, size), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    s = size / 256.0
    # shield: straight top, sides curving to a point at the bottom
    top, left, right = 24 * s, 32 * s, 224 * s
    pts = [(left, top), (right, top), (right, 120 * s), (128 * s, 240 * s), (left, 120 * s)]
    d.polygon(pts, fill=BLUE, outline=BLUE_DARK, width=max(1, int(8 * s)))
    # sword: pommel, grip, cross guard, blade
    cx = 128 * s
    d.ellipse([cx - 14 * s, 196 * s, cx + 14 * s, 224 * s], fill=GOLD, outline=GOLD_DARK, width=max(1, int(3 * s)))
    d.rectangle([cx - 8 * s, 150 * s, cx + 8 * s, 200 * s], fill=GOLD_DARK)
    d.rectangle([cx - 52 * s, 138 * s, cx + 52 * s, 154 * s], fill=GOLD, outline=GOLD_DARK, width=max(1, int(3 * s)))
    d.polygon([(cx - 14 * s, 138 * s), (cx + 14 * s, 138 * s), (cx + 10 * s, 60 * s), (cx, 36 * s), (cx - 10 * s, 60 * s)],
              fill=GOLD, outline=GOLD_DARK, width=max(1, int(3 * s)))
    return im


def main():
    base = draw(256)
    sizes = [(16, 16), (32, 32), (48, 48)]
    ico = os.path.join(ROOT, 'src', 'runtime', 'loader', 'openjoan.ico')
    base.save(ico, format='ICO', sizes=sizes, bitmap_format='bmp')
    im32 = base.resize((32, 32), Image.LANCZOS)
    words = []
    for y in range(32):
        for x in range(32):
            r, g, b, a = im32.getpixel((x, y))
            words.append((a << 24) | (r << 16) | (g << 8) | b)
    inc = os.path.join(ROOT, 'src', 'platform', 'openjoan_icon.inc')
    with open(inc, 'w', newline='\n') as f:
        f.write('// SPDX-License-Identifier: GPL-3.0-or-later\n')
        f.write("// OpenJoan's own window icon, 32 x 32 ARGB, top row first (generated by tools/make_icon.py - do not edit;\n")
        f.write('// the same artwork as src/runtime/loader/openjoan.ico, resource 102). ADR-0002.\n')
        f.write('constexpr int kOpenJoanIconSize = 32;\n')
        f.write('constexpr std::uint32_t kOpenJoanIcon[32 * 32] = {\n')
        for i in range(0, len(words), 8):
            f.write('    ' + ', '.join('0x%08x' % w for w in words[i:i + 8]) + ',\n')
        f.write('};\n')
    print('wrote', os.path.relpath(ico, ROOT), '(%d bytes)' % os.path.getsize(ico), 'and', os.path.relpath(inc, ROOT))


if __name__ == '__main__':
    main()

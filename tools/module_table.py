"""Function table of a module directory, from its registrations (re/check_registrations.py).

  tools/module_table.py src/<dir> [--write]

Prints, per source file of the directory, the registered functions: | address | registration name | module key |
(sorted by address). --write puts the table into src/<dir>/README.md between the lines
`<!-- module-table -->` and `<!-- /module-table -->` (appended with a "## Functions" heading when absent).
"""
import collections
import os
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BEGIN, END = '<!-- module-table -->', '<!-- /module-table -->'


def main():
    d = sys.argv[1].rstrip('/')
    rel = os.path.relpath(os.path.join(ROOT, d), os.path.join(ROOT, 'src'))
    with tempfile.NamedTemporaryFile('r', suffix='.tsv') as t:
        subprocess.run([sys.executable, os.path.join(ROOT, 're', 'check_registrations.py'), '--dump', t.name],
                       check=True, cwd=ROOT, stdout=subprocess.DEVNULL)
        regs = [l.rstrip('\n').split('\t') for l in open(t.name) if l.strip()]
    by_file = collections.defaultdict(list)
    for r in regs:
        if os.path.dirname(r[5]) == rel:
            by_file[r[5]].append(r)
    out = ['Generated by `tools/module_table.py %s --write` from the registrations; %d functions in %d files.'
           % (d, sum(len(v) for v in by_file.values()), len(by_file)), '']
    for f in sorted(by_file):
        out.append('### `%s`' % os.path.basename(f))
        out.append('')
        out.append('| address | registration name | module key |')
        out.append('|---|---|---|')
        # an address written as an expression (fn::va(...)) sorts last, after the numeric ones
        for r in sorted(by_file[f], key=lambda r: (not r[0].startswith('0x'), int(r[0], 16) if r[0].startswith('0x') else 0, r[1])):
            out.append('| `%s` | `%s` | `%s` |' % (r[0], r[1], r[2]))
        out.append('')
    table = '\n'.join(out).rstrip('\n')
    if '--write' not in sys.argv:
        print(table)
        return
    readme = os.path.join(ROOT, d, 'README.md')
    s = open(readme).read() if os.path.exists(readme) else '# %s\n' % d
    block = BEGIN + '\n' + table + '\n' + END
    if BEGIN in s and END in s:
        s = s[:s.index(BEGIN)] + block + s[s.index(END) + len(END):]
    else:
        s = s.rstrip('\n') + '\n\n## Functions\n\n' + block + '\n'
    open(readme, 'w', newline='\n').write(s)
    print('%s: %d files' % (readme, len(by_file)))


if __name__ == '__main__':
    main()

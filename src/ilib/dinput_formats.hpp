// 0x007a78d0: entry i = {&GUID_Key, DIK offset i, DIDFT_OPTIONAL | DIDFT_MAKEINSTANCE(i) | DIDFT_BUTTON, 0}.
struct KeyboardObjects {
    ObjectDataFormat o[256];
    constexpr KeyboardObjects() : o{} {
        for (std::uint32_t i = 0; i < 256; ++i) o[i] = {&kGuidKey, i, 0x8000000cu | i << 8, 0};
    }
};
inline constexpr KeyboardObjects kKeyboardObjects{};


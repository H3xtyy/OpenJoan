//
// Batch 113, list 03: statically linked D3DX8 math (d3dx8math, x87 build) inside joan.exe.
//
// Module "d3dx/b113_03". All eleven roots are stateless D3DX8 math routines (__stdcall, pointer
// args, return pOut in eax except QuaternionToAxisAngle). Port P1: portable C++ transcriptions of the original x87
// instruction sequences on joan::fp (src/fp/pc24.hpp: PC24 rounding with the register's extended exponent
// range, x87 NaN rules, fsincos with the FPU's 66-bit pi, the `test ah,0x41; jp` epsilon tests as the
// gt_or_unordered / le_or_unordered predicates). One call per x87 operation and every memory access in the original
// order (generated by re/p1/d3dx/gen.py from the former inline-assembly bodies, control flow by hand), so in == out aliasing
// behaves as in D3DX; `l[i]` is the original's stack frame, l[0] at [ebp - frame size]. Proof: re/p1/d3dx (README).
//
// D3DXQuaternionSlerp (P2) multiplies two fsin results (64-bit precision) by a PC24 value on the x87 stack: modelled
// with the 64-bit software x87 of src/fp/x87_64.hpp. The CPU's fsin is not correctly rounded to 64 bits (1.5 % of
// float inputs in [2^-7, pi] differ from the correctly rounded value, re/p1/d3dx), so the products' 24-bit rounding
// can differ from the original's when a product lies within ~2^-64 of a rounding midpoint: rates in re/p2/slerp.
//
//   0x00767eeb D3DXQuaternionSlerp(out, q1, q2, t)          ret 0x10  calls QuaternionDot 0x767ac9
//   0x007680a8 D3DXPlaneNormalize(out, p)                    ret 0x8
//   0x007681df D3DXPlaneFromPointNormal(out, point, normal)  ret 0xc
//   0x007683ee D3DXVec3Normalize(out, v)                     ret 0x8   (via a local: in place OK)
//   0x00768495 D3DXVec3TransformCoord(out, v, m)             ret 0xc
//   0x0076883c D3DXMatrixRotationAxis(out, axis, angle)      ret 0xc   calls Vec3Normalize
//   0x00768c7c D3DXMatrixLookAtLH(out, eye, at, up)          ret 0x10  calls Vec3Normalize and the
//                                                                      cross product 0x005beef0
//                                                                      (thunk 0x00402220, cdecl)
//   0x00768e60 D3DXMatrixReflect(out, plane)                 ret 0x8   calls PlaneNormalize
//   0x00768f1f D3DXQuaternionToAxisAngle(q, axis, angle)     ret 0xc   void; calls
//                                                                      QuaternionLengthSq 0x767a9b
//                                                                      and CRT _CIacos 0x7b2260
//   0x00768f9c D3DXQuaternionRotationAxis(out, axis, angle)  ret 0xc   calls Vec3Normalize
//   0x00768ff8 D3DXPlaneFromPoints(out, p1, p2, p3)          ret 0x10  calls cross 0x005beef0
//                                                                      (thunk 0x00402220),
//                                                                      Vec3Normalize
//
// Calls: Vec3Normalize / PlaneNormalize are the functions below (called directly: pure, identical to whatever is
// installed at their addresses); QuaternionLengthSq 0x767a9b and QuaternionDot 0x767ac9 are inlined (pure; same
// operations as lib/imports/import_stubs.cpp's transcriptions, results kept unrounded like their st0 returns); the
// cross product goes through joan::orig::vec_cross_5beef0 (game code, whatever is installed); _CIacos(w) through
// joan::orig::libc::acos 0x007b2274 (same CRT body; _CIacos only takes its argument from st0 - here the float w,
// exactly a double - and returns the same st0; checked over all 2^32 w in re/p1/d3dx).
// The float constants are the .rdata values at 0x9e2fe0..0x9e301c (bit patterns).
//
// Installation note: library functions are entry-patched (no thunks). patch_entry accepts any entry
// in 0x765000..0x7d5000 that passes re/check_lib_entries.py, so all eleven install (checked: each
// entry follows the previous function's ret, is reached only by direct calls, and nothing jumps
// into entry+1..4; 0x768ff8 is a real entry - functions.json merges it with 0x769077.. - called
// from game 0x60d95d and D3DX 0x7734cf / 0x773a13, our en3d_helpers3.cpp also calls it).
// No counters: hot math routines.


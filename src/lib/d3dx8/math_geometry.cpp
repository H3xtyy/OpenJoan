    const R t8 = ld(l[0]);
    const R t9 = fmul(t8, t2);
    const R t10 = fadd(t9, t7);
    wr(out, 0x0, st(t10));
    const R t11 = fmul_m(t4, l[0]);
    wr(out, 0x4, st(t11));
    const R t12 = fmul_m(t6, l[0]);
    wr(out, 0x8, st(t12));

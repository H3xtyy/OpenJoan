    wr(out, 0x18, w3);
    wr(out, 0x8, 0x00000000u);
    wr(out, 0xc, 0x00000000u);
    wr(out, 0x10, 0x00000000u);
    const R t4 = ld(l[2]);
    wr(out, 0x14, st(t4));
    wr(out, 0x1c, 0x00000000u);
    wr(out, 0x20, 0x00000000u);
    const R t5 = ld(l[3]);

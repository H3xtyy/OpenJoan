// Original library sources (re/attribution.csv original_file, under lib/): d3dx8/d3dx8math.cpp.
//
// Batch 113, list 02: statically linked D3DX8 maths (x87 code path) inside joan.exe.
//
// Range 0x007669fb..0x00767c5d is the D3DX8 (d3dx8.lib, DirectX 8.0/8.1 SDK) x87 implementation
// of the matrix / quaternion helpers. The game calls these entry points directly (no
// incremental-link thunks; D3DX8 has no CPU dispatch table in this build for these functions:
// game code and our C++ do `call 0x007669fb` etc.). All are stdcall, return pOut in eax.
//
// Every function here is a pure function of its arguments (no globals, no errno, no heap). Port P1: portable C++
// transcriptions of the original x87 instruction sequences on joan::fp (src/fp/pc24.hpp: PC24 rounding with the
// register's extended exponent range, x87 NaN rules, fld/fstp quietening of copied SNaN elements, fsincos with the
// FPU's 66-bit pi). Each x87 operation of the original is one call, in the original order; every memory access is
// made in the original order too (generated by re/p1/d3dx/gen.py from the former inline-assembly bodies, control flow by
// hand), so in == out aliasing behaves as in D3DX. `l[i]` is the original's stack frame, l[0] at [ebp - frame size].
// Proof: re/p1/d3dx (freestanding i386 harness calling the original code in joan.exe; README there).
// The .rdata constants are the bit patterns of 0x009e2ffc 2.0f, 0x009e2ff0 0.5f, 0x009e2fe8 1.0f, 0x009e3004 0.0f,
// 0x009e3000 0.25f.
//
// Module "d3dx/b113_02" (all twelve; patch_entry accepts any library-range entry >= 5 bytes with
// no outside jump into entry+1..4 - re/check_lib_entries.py reports all of these safe):
//     0x007669fb D3DXMatrixMultiply(out, m1, m2)             ret 0xc  (aliasing: out == m2 ->
//                column-wise path; out == m1 == m2 -> m2 copied to a 64-byte local first)
//     0x00766b4b D3DXMatrixInverse(out, pDeterminant, m)     ret 0xc  (cofactor expansion; stores
//                det to *pDeterminant when non-null; 1/det tested with CRT _finite 0x007b770f (inlined:
//                a pure exponent test of the float); returns NULL when not finite, out untouched)
//     0x00766f90 D3DXMatrixRotationX(out, angle)             ret 8    (fsincos)
//     0x0076700a D3DXMatrixRotationY(out, angle)             ret 8    (fsincos)
//     0x00767085 D3DXMatrixRotationZ(out, angle)             ret 8    (fsincos)
//     0x00767101 D3DXMatrixRotationQuaternion(out, q)        ret 8
//     0x007674a4 D3DXMatrixPerspectiveFovLH(out, fovy, aspect, zn, zf) ret 0x14 (fsincos)
//     0x00767967 D3DXQuaternionRotationMatrix(out, m)        ret 8    (fsqrt, trace > 0 test
//                `fcom 0.0; test ah,0x41; jne` = trace <= 0 or NaN -> largest-diagonal path)
//     0x00766ade D3DXMatrixTranspose(out, m)                 ret 8
//     0x00766f34 D3DXMatrixTranslation(out, x, y, z)         ret 0x10
//     0x00767723 D3DXMatrixOrthoLH(out, w, h, zn, zf)        ret 0x14
//     0x00767bc7 D3DXQuaternionMultiply(out, q1, q2)         ret 0xc
//

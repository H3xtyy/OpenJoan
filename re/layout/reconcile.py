#!/usr/bin/env python3
"""Resolves conflicting function -> class assignments between spec files (docs/X64.md): for each function that
two groups assign differently, the class whose layout covers the most of the function's own accesses wins (ties:
the label's class, then the owner of the class). Writes re/layout/spec/zz_reconcile.json (loaded last)."""
import collections, glob, json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import check_spec as K
paths = sorted(p for p in glob.glob(os.path.join(HERE, 'spec', '*.json')) if not p.endswith('zz_reconcile.json'))
classes, owner, _, problems = K.load_specs(paths)
L = K.Layout(classes)
maps = collections.defaultdict(dict)
for p in paths:
    for a, c in json.load(open(p)).get('functions', {}).items():
        maps[f'{int(a, 16):#x}'][os.path.basename(p)[:-5]] = c
rank = {os.path.basename(p)[:-5]: i for i, p in enumerate(paths)}
def score(a, cls):
    if cls is None or cls not in classes:
        return -1
    bm = L.bytes_of(cls); ok = tot = 0
    for path, off, width, kind, n in K.F[a]['asm']:
        if path or width == 0:
            continue
        tot += 1
        ok += all(b in bm for b in range(off, off + width))
    return ok / tot if tot else 0
out, log = {}, []
for a, v in sorted(maps.items()):
    cands = set(v.values())
    if len(cands) < 2:
        continue
    lab = K.F.get(a, {}).get('class')
    last = {c: max(rank[g] for g, c2 in v.items() if c2 == c) for c in cands}
    best = max(cands, key=lambda c: (round(score(a, c), 3), last[c]))
    out[a] = best
    log.append(f'{a} {K.F.get(a, {}).get("name")}: ' + ', '.join(f'{g}={c}({score(a, c):.2f})' for g, c in sorted(v.items())) + f' -> {best}')
json.dump({'group': 'zz_reconcile', 'classes': [], 'functions': out,
           'notes': 'generated by re/layout/reconcile.py'}, open(os.path.join(HERE, 'spec', 'zz_reconcile.json'), 'w'), indent=1)
print('\n'.join(log)); print(len(out), 'conflicts resolved')

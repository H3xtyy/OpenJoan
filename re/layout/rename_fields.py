"""Rename layout fields (`Unit::u32_2a` -> `Unit::last_update_ms`) from a committed table.

Usage (repository root, clean working tree):
  re/layout/rename_fields.py <table.csv> [--build build/linux-x64] [--jobs 8] [--no-gen]

The table is CSV: class, offset, old_name, new_name, evidence ('#' comment lines allowed). For every row:
 1. re/layout/layouts.json and the spec file the class is defined in (its `defined_in`) get the new name, by class and
    offset;
 2. classes typed by hand (no generated header: src/original/<x>.hpp) get it in their struct, classes with a generated
    header are regenerated by re/layout/gen_types.py (which is not round-trip clean: everything it changes outside the
    named classes' files is restored);
 3. every use is found by the compiler, not by text: all translation units of the build's compile_commands.json are
    checked with clang++ -fsyntax-only, and each "no member named 'old' in 'Class'" position is rewritten at its exact
    line and column; repeated until a whole pass reports none. A placeholder name shared by several classes is therefore
    renamed only for the class in the table.

Generated save records (src/save/gen) are fixed the same way; re/save/gen_save.py reads the layouts, so it keeps them.
"""
import argparse
import collections
import concurrent.futures as cf
import csv
import json
import os
import re
import shlex
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)


def sh(*a):
    return subprocess.run(a, cwd=ROOT, capture_output=True, text=True).stdout


def rename_in_json(path, cls, off, old, new):
    s = open(path).read()
    pos = [m.start() for m in re.finditer(r'"class":\s*"%s"' % re.escape(cls), s)]
    pat = re.compile(r'("off":\s*"%s"[^{}]*?"name":\s*")%s(")' % (re.escape(off), re.escape(old)), re.S)
    pat2 = re.compile(r'("name":\s*")%s("[^{}]*?"off":\s*"%s")' % (re.escape(old), re.escape(off)), re.S)
    for p in pos:
        end = s.find('"class":', p + 8)
        end = len(s) if end < 0 else end
        block = s[p:end]
        b2, n = pat.subn(lambda m: m.group(1) + new + m.group(2), block, count=1)
        if not n:
            b2, n = pat2.subn(lambda m: m.group(1) + new + m.group(2), block, count=1)
        if n:
            open(path, 'w').write(s[:p] + b2 + s[end:])
            return True
    return False


def tu_errors(entry):
    """[(file, line, col, old, class)] of one translation unit"""
    args = shlex.split(entry['command']) if 'command' in entry else list(entry['arguments'])
    out, skip = [], False
    for a in args[1:]:
        if skip:
            skip = False
            continue
        if a in ('-o', '-c'):
            skip = True
            continue
        if a == '-Winvalid-pch':
            continue
        if a.endswith('cmake_pch.hxx'):
            out.pop()
            continue
        out.append(a)
    r = subprocess.run(['clang++', '-fsyntax-only', '-w', '-ferror-limit=0'] + out + [entry['file']],
                       cwd=entry['directory'], capture_output=True, text=True)
    res = []
    for m in re.finditer(r"^(.+?):(\d+):(\d+): error: no member named '(\w+)' in '([^']+)'", r.stderr, re.M):
        res.append((os.path.normpath(os.path.join(entry['directory'], m.group(1))), int(m.group(2)), int(m.group(3)),
                    m.group(4), m.group(5)))
    others = [l for l in r.stderr.splitlines() if ': error:' in l and 'no member named' not in l]
    return res, others


def finish_with_gcc(build, new_of):
    """Builds `build` (ninja -k 0) and rewrites each `has no member named` use GCC reports, until none is left."""
    for _ in range(6):
        o = subprocess.run(['cmake', '--build', build, '-j8', '--', '-k', '0'], cwd=ROOT, capture_output=True,
                           text=True).stdout
        sites = collections.defaultdict(set)
        for m in re.finditer(r"^(\S+?):(\d+):(\d+): error: .*?(?:struct|class) (?:\w+::)*(\w+)’ has no member named ‘(\w+)’",
                             o, re.M):
            f, ln, _c, cls, old = m.groups()
            if (cls, old) in new_of:
                f = os.path.normpath(f if f.startswith('/') else os.path.join(ROOT, build, f))
                sites[f].add((int(ln), old, new_of[(cls, old)]))
        n = sum(len(v) for v in sites.values())
        print('gcc %s: %d uses, %d errors in all' % (build, n, len(re.findall(r'error:', o))))
        if not n:
            return
        for f, ss in sites.items():
            lines = open(f, encoding='utf-8', errors='surrogateescape').read().split('\n')
            for ln, old, new in ss:
                lines[ln - 1] = re.sub(r'\b%s\b' % old, new, lines[ln - 1])
            open(f, 'w', encoding='utf-8', errors='surrogateescape', newline='').write('\n'.join(lines))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('table')
    ap.add_argument('--build', default='build/linux-x64')
    ap.add_argument('--jobs', type=int, default=8)
    ap.add_argument('--no-gen', action='store_true')
    ap.add_argument('--alias', action='append', default=[], metavar='DERIVED=BASE',
                    help='uses reported through a derived class (Hero=Unit)')
    ap.add_argument('--uses-only', action='store_true', help='only the compiler-driven step (the headers are done)')
    ap.add_argument('--finish', action='append', default=[], metavar='BUILD_DIR',
                    help='after the Clang passes, build these directories and fix what GCC still reports (GCC lists '
                         'every use inside a macro at once; a 32-bit build dir also covers the 32-bit-only code)')
    a = ap.parse_args()
    rows = list(csv.DictReader(l for l in open(os.path.join(ROOT, a.table)) if not l.startswith('#')))
    if not a.uses_only and sh('git', 'status', '--porcelain', 'src', 're/layout').strip():
        sys.exit('src/ or re/layout/ has uncommitted changes: commit first (the tool restores what the generator rewrites)')
    from gen_types import snake  # noqa: E402
    layouts = os.path.join(HERE, 'layouts.json')
    data = json.load(open(layouts))['classes']
    want = collections.defaultdict(dict)
    for r in rows:
        cls, off, old, new = r['class'], r['offset'], r['old_name'], r['new_name']
        if a.uses_only:
            want[cls][old] = new
            continue
        if not any(f['name'] == old and int(f['off'], 16) == int(off, 16) for f in data[cls]['fields']):
            sys.exit('%s::%s is not at %s in layouts.json' % (cls, old, off))
        if any(f['name'] == new for f in data[cls]['fields']):
            sys.exit('%s already has a field %s' % (cls, new))
        off = next(f['off'] for f in data[cls]['fields'] if f['name'] == old)
        if not rename_in_json(layouts, cls, off, old, new):
            sys.exit('layouts.json: %s %s' % (cls, old))
        spec = os.path.join(HERE, 'spec', data[cls].get('defined_in') or '')
        if not rename_in_json(spec, cls, off, old, new):
            print('note: %s::%s not found in %s' % (cls, old, data[cls].get('defined_in')))
        want[cls][old] = new
    # hand-typed classes: the struct in src/original/*.hpp
    gen_classes = []
    hand_headers = []
    for cls, ren in (want.items() if not a.uses_only else ()):
        gen_hpp = os.path.join(ROOT, 'src', 'original', 'gen', snake(cls) + '_fields.inc')
        if os.path.exists(gen_hpp):
            gen_classes.append(cls)
            continue
        hdr = None
        for f in os.listdir(os.path.join(ROOT, 'src', 'original')):
            p = os.path.join(ROOT, 'src', 'original', f)
            if f.endswith('.hpp') and re.search(r'^struct %s\b' % cls, open(p, errors='ignore').read(), re.M):
                hdr = p
                break
        if not hdr:
            sys.exit('no header for %s' % cls)
        s = open(hdr).read()
        i = re.search(r'^struct %s\b' % cls, s, re.M).start()
        j = s.index('\n};', i)
        body = s[i:j]
        for old, new in ren.items():
            body, n = re.subn(r'\b%s\b' % old, new, body)
            if not n:
                print('note: %s not in %s' % (old, hdr))
        open(hdr, 'w').write(s[:i] + body + s[j:])
        hand_headers.append(os.path.relpath(hdr, ROOT))
    if gen_classes and not a.no_gen:
        hand_text = {p: open(os.path.join(ROOT, p)).read() for p in hand_headers}  # gen_types.py also rewrites those
        subprocess.run([sys.executable, os.path.join(HERE, 'gen_types.py')], cwd=ROOT, check=True, stdout=subprocess.DEVNULL)
        keep = {'src/original/gen/%s%s' % (snake(c), x) for c in gen_classes for x in ('.hpp', '_fields.inc')}
        for line in sh('git', 'status', '--porcelain', 'src/original', 're/layout').splitlines():
            p = line[3:]
            if p.startswith('src/original/') and p not in keep and p not in hand_text:
                subprocess.run(['git', 'checkout', '-q', '--', p], cwd=ROOT, check=True)
            elif p.startswith('re/layout/') and p.endswith('.txt'):
                subprocess.run(['git', 'checkout', '-q', '--', p], cwd=ROOT, check=False)
        for p, text in hand_text.items():
            open(os.path.join(ROOT, p), 'w').write(text)
    # uses: compiler-driven
    new_of = {(c.split('::')[-1], o): n for c, r in want.items() for o, n in r.items()}
    for al in a.alias:
        d, b = al.split('=')
        new_of.update({(d, o): n for (c, o), n in list(new_of.items()) if c == b})
    cc = [e for e in json.load(open(os.path.join(ROOT, a.build, 'compile_commands.json')))
          if e['file'].startswith(os.path.join(ROOT, 'src')) or e['file'].startswith(os.path.join(ROOT, 'tests'))]
    for round_no in range(1, 8):
        with cf.ThreadPoolExecutor(a.jobs) as ex:
            results = list(ex.map(tu_errors, cc))
        sites = collections.defaultdict(set)
        other = collections.Counter()
        unknown = set()
        for res, others in results:
            for f, ln, col, old, cname in res:
                key = (cname.split('::')[-1], old)
                if key in new_of:
                    sites[f].add((ln, col, old, new_of[key]))
                else:
                    unknown.add((f, ln, old, cname))
            for o in others:
                other[o] += 1
        n = sum(len(v) for v in sites.values())
        print('pass %d: %d uses in %d files; %d other errors' % (round_no, n, len(sites), len(other)))
        if not n:
            for u in sorted(unknown)[:30]:
                print('  unresolved:', u)
            for o, _ in other.most_common(30):
                print('  error:', o[:200])
            break
        for f, ss in sites.items():
            lines = open(f, encoding='utf-8', errors='surrogateescape').read().split('\n')
            for ln, col, old, new in sorted(ss, reverse=True):
                raw = lines[ln - 1].encode('utf-8', 'surrogateescape')
                i = col - 1
                if raw[i:i + len(old)] != old.encode():
                    # inside a macro argument Clang reports the macro's column: the one whole-word occurrence on the line
                    hits = [m.start() for m in re.finditer(rb'\b%s\b' % old.encode(), raw)]
                    if len(hits) != 1:
                        print('  position mismatch', f, ln, col, old)
                        continue
                    i = hits[0]
                lines[ln - 1] = (raw[:i] + new.encode() + raw[i + len(old):]).decode('utf-8', 'surrogateescape')
            open(f, 'w', encoding='utf-8', errors='surrogateescape', newline='').write('\n'.join(lines))
    for b in a.finish:
        finish_with_gcc(b, new_of)
    return 0


if __name__ == '__main__':
    sys.exit(main())

# gen.py CLASS ACCESSOR HEADER_INC  -> writes src/original/gen/<inc>, spec_<cls>.py for mod2
import json,sys,re
S='/tmp/openjoan-facades/'
ROOT='./'
cls,acc,inc=sys.argv[1],sys.argv[2],sys.argv[3]
existing=set(sys.argv[4].split(',')) if len(sys.argv)>4 and sys.argv[4] else set()
sig=json.load(open(S+'r9/sig_%s.json'%cls))
# parameters the replacement declares as integers but that carry float bits (callers pass floats)
FLOATS=json.load(open(S+'r9/floats.json')) if __import__('os').path.exists(S+'r9/floats.json') else {}
for n,idx in FLOATS.items():
    if n in sig:
        for i in idx: sig[n][1][i]='float'
KIND={'std::int32_t':'i32','std::uint32_t':'u32','std::int16_t':'i16','std::uint16_t':'u16','void*':'mptr','const char*':'str',
      'float':'f32','double':'f64','std::uint8_t':'u8','std::int8_t':'i8','char':'char'}
W={'std::uint8_t':1,'std::int8_t':1,'char':1,'std::uint16_t':2,'std::int16_t':2}
lines=['// Generated by re/gen_facades.py: typed members for the %s functions game code calls through their slots.'%cls,
       '// Each forwards to the function\'s slot (the registered replacement); included inside struct %s.'%cls,'']
M={}; RW={}
for name,(ret,ps,regname,real) in sorted(sig.items(),key=lambda kv:kv[1][3]):
    if any(p=='bool' for p in ps) or ret=='bool': continue
    meth=name[len(cls)+1:]
    if meth in existing or not re.match(r'^[A-Za-z_]\w*$',meth): meth=meth+'_slot'
    args=', '.join('%s a%d'%(p,i) for i,p in enumerate(ps)); call=''.join(', a%d'%i for i in range(len(ps)))
    body=('::joan::call::thiscall<%s>(::joan::fn::%s, this%s)'%(ret,name,call))
    lines.append('/// 0x%08x %s'%(real,regname))
    lines.append('%s %s(%s) { %s%s; }'%(ret,meth,args,'' if ret=='void' else 'return ',body))
    M[name]=(acc,meth,[KIND[p] for p in ps],ret!='void')
    if ret in W: RW[meth]=W[ret]
open(ROOT+'src/original/gen/'+inc,'w').write('\n'.join(lines)+'\n')
open(S+'r1/spec_r9_%s.py'%cls.lower(),'w').write('M=%r\nINCLUDE=\'"../original/direct.hpp"\'\nSKIP_FILES=[]\nDEFAULTS={}\nNARROW=()\nRET_WIDTH=%r\n'%(M,RW))
print(len(M),'methods')

#!/usr/bin/env python3
"""The 64-bit layout of joan.exe's data image (docs/X64.md image): src/data/image_xlate.inc.

joan_image keeps its original (x86) layout byte for byte in the 32-bit build. In the 64-bit build every stored
pointer of struct layout::Image (pointer members, `uptr`, pointers inside the class objects of .bss, the IAT slots)
is 8 bytes, so everything after it moves. The compiler decides that layout; this tool asks it (libclang over
src/data/layout.hpp for i686 and x86_64, re/image/probe.py), pairs the pointer leaves of both layouts and writes
the piecewise-linear map  original address -> offset in the x64 joan_image:

    JOAN_IMAGE_X64_SIZE(0xa83fcu)
    JOAN_XLATE(0x009cf000u, 0x0u)       a run: addresses va.. map to off + (address - va)
    JOAN_XLATE(0x009cf82cu, 0x830u)     (after each pointer: the next run starts 4 bytes later on x64)

An address inside a pointer maps into the low half of the 8-byte slot (little-endian: the same bytes). Consumers:
src/runtime/image.hpp (img::Addr::off, constexpr), src/runtime/loader/data_image.cpp (relocation, section CRCs on x64),
the compiler (each stored pointer of the committed source is a uptr, 8 bytes on x64).

Checks: both layouts have the same pointer leaves in the same order, the bytes between two pointers have the same
size in both, every data_relocs.inc word is a pointer leaf.

    re/image/gen_xlate.py [--data src/data] [-o src/data/image_xlate.inc]
"""
import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import probe  # noqa: E402

KVA = 0x9cf000


def build(data_dir):
    text = '#include "%s"\n' % os.path.abspath(os.path.join(data_dir, 'layout.hpp'))
    s86, l86 = probe.walk(text, 'joan::data::layout::Image', 'x86')
    s64, l64 = probe.walk(text, 'joan::data::layout::Image', 'x64')
    problems = []
    if len(l86) != len(l64):
        problems.append(f'pointer leaves differ: {len(l86)} (x86) vs {len(l64)} (x64)')
    runs = [(KVA, 0)]
    prev86, prev64 = 0, 0
    for (o86, z86), (o64, z64) in zip(l86, l64):
        if z86 != 4 or z64 != 8:
            problems.append(f'leaf at +{o86:#x}: size {z86} / {z64}')
        if o86 - prev86 != o64 - prev64:
            problems.append(f'bytes before the leaf at +{o86:#x} differ in size: {o86 - prev86:#x} / {o64 - prev64:#x}')
        prev86, prev64 = o86 + 4, o64 + 8
        runs.append((KVA + o86 + 4, o64 + 8))
    if s86 - prev86 != s64 - prev64:
        problems.append('tail sizes differ')
    leaf = {KVA + o for o, _ in l86}
    for line in open(os.path.join(data_dir, 'data_relocs.inc')):
        m = re.match(r'JOAN_DATA_RELOC\((0x[0-9a-f]+)u', line)
        if m and int(m.group(1), 16) not in leaf:
            problems.append(f'reloc {m.group(1)} is not a pointer member of the layout')
    return s86, s64, runs, len(l86), problems


def text(s86, s64, runs, nleaves):
    L = ['// Generated by re/image/gen_xlate.py from src/data/layout.hpp (the compiler\'s x86 and x64 layouts) - do not edit.',
         '// joan_image on x64: %d pointer slots widen from 4 to 8 bytes, size 0x%x -> 0x%x. X-macros: define' % (
             nleaves, s86, s64),
         '//   JOAN_IMAGE_X64_SIZE(size)   sizeof(layout::Image) on x64',
         '//   JOAN_XLATE(va, off)         a run: original addresses va.. (up to the next run) are at off + (address - va)',
         '// before including. Runs are sorted by va; the first starts at the image (0x%06x, offset 0).' % KVA,
         '#ifndef JOAN_IMAGE_X64_SIZE',
         '#define JOAN_IMAGE_X64_SIZE(size)',
         '#define JOAN_XLATE_UNDEF_SIZE',
         '#endif',
         '#ifndef JOAN_XLATE',
         '#define JOAN_XLATE(va, off)',
         '#define JOAN_XLATE_UNDEF_RUN',
         '#endif',
         'JOAN_IMAGE_X64_SIZE(0x%xu)' % s64]
    L += ['JOAN_XLATE(0x%06xu, 0x%xu)' % r for r in runs]
    L += ['#ifdef JOAN_XLATE_UNDEF_SIZE', '#undef JOAN_IMAGE_X64_SIZE', '#undef JOAN_XLATE_UNDEF_SIZE', '#endif',
          '#ifdef JOAN_XLATE_UNDEF_RUN', '#undef JOAN_XLATE', '#undef JOAN_XLATE_UNDEF_RUN', '#endif']
    return '\n'.join(L) + '\n'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--data', default=os.path.join(probe.SRC, 'data'))
    ap.add_argument('-o')
    a = ap.parse_args()
    s86, s64, runs, n, problems = build(a.data)
    if problems:
        sys.exit('gen_xlate: ' + '\n  '.join(problems[:30]))
    out = a.o or os.path.join(a.data, 'image_xlate.inc')
    open(out, 'w', newline='\n').write(text(s86, s64, runs, n))
    print(f'image x86 {s86:#x}, x64 {s64:#x}: {n} pointer slots, {len(runs)} runs -> {out}')


if __name__ == '__main__':
    main()

#!/usr/bin/env python3
"""Generate joan_re.exe's own copy of joan.exe's image layout, import table and icon ([Loader] Data=embedded,
STANDALONE.md stage S6a). Run once, offline; the outputs are committed source - joan.exe is never read at build time
or by joan_re.exe in that mode. The initial contents of .rdata / .data are typed C++ since stage S6b, generated by
re/gen_data_curated.py into src/data/ (this script's former raw word output data_image.inc is gone).

Usage (from the repository root):
  gen_data_image.py <joan.exe> [hook dir]          (hook dir defaults to src/ next to this script's re/)

Outputs:
  <hook>/image_layout.inc  image layout: the PE header fields our synthetic header repeats and the section table.
                           Consumer: src/runtime/loader/data_image.cpp.
  <hook>/import_table.inc  the import table: DLLs in joan.exe's descriptor order and, per IAT slot, the function name
                           or ordinal. Consumer: src/runtime/loader/data_image.cpp (resolution in src/runtime/loader/joan_re.cpp).
  <hook>/loader/joan.ico   icon group 102 (one 32x32 image, RT_ICON 1) as an .ico file for src/runtime/loader/joan_re.rc.
Dialog 101 is written by hand in src/runtime/loader/joan_re.rc (decoded from joan.exe's template; same bytes, checked with
llvm-rc for S6a).

What is NOT carried over (nothing reads it, checked for S6a): joan.exe's headers (the loader writes its own header at
0x00400000, built from the fields below - see data_image.cpp), .idata other than the IAT slots (descriptors, name
tables, hint/name strings; no relocated dword of the image and no constant of our C++ points into them), .rsrc
(moved into joan_re.rc), .reloc (fixed base), .text (stage S5: generated).

gen_data_image.py --check <joan.exe> <image.bin> <imports.txt> [dead.txt]: compare an image dump and import table
with joan.exe. The dump came from the Linux harness re/data_image_harness.cpp, deleted in OpenJoan Phase 1 together
with image_layout.inc: tests/data_image_reference_test now compares the committed image with the reference joan.exe
directly. The mode is kept for a maintainer with an old dump; nothing in the repository produces one.
"""
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from pe import PE  # noqa: E402

BASE = 0x00400000
CONTENT = ('.rdata', '.data')  # sections whose initial bytes are embedded


def header_fields(p):
    d = p.data
    pe = struct.unpack_from('<I', d, 0x3C)[0]
    machine, nsec, stamp, _, _, optsz, chars = struct.unpack_from('<HHIIIHH', d, pe + 4)
    o = pe + 24
    names = ('magic major_linker minor_linker size_of_code size_of_init size_of_uninit entry base_of_code base_of_data '
             'image_base section_align file_align major_os minor_os major_image minor_image major_subsystem '
             'minor_subsystem win32_version size_of_image size_of_headers checksum subsystem dll_characteristics '
             'stack_reserve stack_commit heap_reserve heap_commit loader_flags rva_count').split()
    vals = struct.unpack_from('<HBBIIIIIIIIIHHHHHHIIIIHHIIIIII', d, o)
    f = dict(zip(names, vals))
    f.update(machine=machine, sections=nsec, timestamp=stamp, optional_size=optsz, characteristics=chars)
    return f


def c_string(s):
    out = []
    for ch in s:
        if ch in '\\"':
            out.append('\\' + ch)
        elif ch == '?':
            out.append('\\?')  # no trigraph can form
        elif 0x20 <= ord(ch) < 0x7F:
            out.append(ch)
        else:
            out.append('\\x%02x' % ord(ch))
    return '"' + ''.join(out) + '"'


def imports_in_order(p):
    """[(dll, [(slot va, ordinal or 0, name or None)])] in descriptor order."""
    d = p.data
    rva, _ = p.dirs[1]
    o = p.rva2off(rva)
    out = []
    while True:
        oft, _, _, name, ft = struct.unpack_from('<IIIII', d, o)
        if name == 0:
            break
        dll = p.cstr(BASE + name).decode()
        names = oft if oft else ft
        funcs = []
        i = 0
        while True:
            v = p.u32(BASE + names + 4 * i)
            if v == 0:
                break
            slot = BASE + ft + 4 * i
            if v & 0x80000000:
                funcs.append((slot, v & 0xFFFF, None))
            else:
                funcs.append((slot, 0, p.cstr(BASE + v + 2).decode()))
            i += 1
        out.append((dll, funcs))
        o += 20
    return out


def resources(p):
    """{(type, id): bytes} of joan.exe's resource tree (numeric ids only, which is all it has)."""
    d = p.data
    rva, _ = p.dirs[2]
    base = p.rva2off(rva)
    res = {}

    def walk(off, path):
        nn, ni = struct.unpack_from('<HH', d, base + off + 12)
        for i in range(nn + ni):
            name, od = struct.unpack_from('<II', d, base + off + 16 + 8 * i)
            assert not name & 0x80000000, 'named resource'
            if od & 0x80000000:
                walk(od & 0x7FFFFFFF, path + [name])
            else:
                drva, size, _, _ = struct.unpack_from('<IIII', d, base + od)
                res[(path[0], path[1], name)] = p.data[p.rva2off(drva):p.rva2off(drva) + size]
    walk(0, [])
    return res


def write_ico(p, path):
    res = resources(p)
    keys = sorted(res)
    assert keys == [(3, 1, 1033), (5, 101, 1033), (14, 102, 1033)], keys  # icon 1, dialog 101, group icon 102
    grp = res[(14, 102, 1033)]
    reserved, typ, count = struct.unpack_from('<HHH', grp, 0)
    assert (reserved, typ, count) == (0, 1, 1)
    entries = []
    images = []
    offset = 6 + 16 * count
    for i in range(count):
        e = grp[6 + 14 * i:6 + 14 * (i + 1)]
        nid = struct.unpack_from('<H', e, 12)[0]
        img = res[(3, nid, 1033)]
        assert struct.unpack_from('<I', e, 8)[0] == len(img)
        entries.append(e[:12] + struct.pack('<I', offset))
        images.append(img)
        offset += len(img)
    blob = struct.pack('<HHH', 0, 1, count) + b''.join(entries) + b''.join(images)
    open(path, 'wb').write(blob)
    return len(blob)


def generate(exe, hook):
    p = PE(exe)
    h = header_fields(p)
    assert h['image_base'] == BASE and h['timestamp'] == 0x400BA40A, 'not the supported joan.exe build'
    L = []
    w = L.append
    w('// Generated by re/gen_data_image.py from joan.exe (timestamp 0x%08X) - do not edit.' % h['timestamp'])
    w('// [Loader] Data=embedded (STANDALONE.md S6a): the layout of joan.exe\'s image that joan_re.exe rebuilds at')
    w('// 0x00400000 - the PE header fields our synthetic header repeats and the section table. Included by')
    w('// src/runtime/loader/data_image.cpp inside its namespace (types HeaderFields, Section declared there). The initial')
    w('// contents of .rdata / .data are src/data/*.cpp (re/gen_data_curated.py, stage S6b).')
    w('')
    w('constexpr HeaderFields kHeaderFields = {')
    for k in ('timestamp', 'characteristics', 'major_linker', 'minor_linker', 'size_of_code', 'size_of_init',
              'size_of_uninit', 'entry', 'base_of_code', 'base_of_data', 'image_base', 'section_align', 'file_align',
              'major_os', 'minor_os', 'major_image', 'minor_image', 'major_subsystem', 'minor_subsystem',
              'size_of_image', 'size_of_headers', 'subsystem', 'dll_characteristics', 'stack_reserve', 'stack_commit',
              'heap_reserve', 'heap_commit'):
        w('    0x%08xu,  // %s' % (h[k], k))
    w('};')
    w('')
    w('// name, virtual address (RVA), virtual size, characteristics (protection), raw size in joan.exe')
    w('const Section kSections[] = {')
    table = struct.unpack_from('<I', p.data, 0x3C)[0] + 24 + h['optional_size']
    for i, (name, va, vs, ro, rs) in enumerate(p.sections):
        chars = struct.unpack_from('<I', p.data, table + 40 * i + 36)[0]
        w('    {%s, 0x%08xu, 0x%08xu, 0x%08xu, 0x%08xu},' % (c_string(name), va, vs, chars, rs))
    w('};')
    open(os.path.join(hook, 'image_layout.inc'), 'w', newline='\n').write('\n'.join(L) + '\n')

    imps = imports_in_order(p)
    L = []
    w = L.append
    w('// Generated by re/gen_data_image.py from joan.exe (timestamp 0x%08X) - do not edit.' % h['timestamp'])
    w('// [Loader] Data=embedded (STANDALONE.md S6a): joan.exe\'s import table. DLLs in the order of its import descriptors')
    w('// (= the order the loader loads them); per IAT slot: DLL index, ordinal (0 = by name), name. Included by')
    w('// src/runtime/loader/data_image.cpp inside its namespace (type Import declared there).')
    w('')
    w('const char* const kImportDlls[] = {')
    for dll, _ in imps:
        w('    %s,' % c_string(dll))
    w('};')
    w('')
    w('const Import kImports[] = {')
    n = 0
    for di, (dll, funcs) in enumerate(imps):
        w('    // %s: %u' % (dll, len(funcs)))
        for slot, ordinal, name in funcs:
            w('    {0x%08xu, %u, %u, %s},' % (slot, di, ordinal, c_string(name) if name else 'nullptr'))
            n += 1
    w('};')
    open(os.path.join(hook, 'runtime', 'import_table.inc'), 'w', newline='\n').write('\n'.join(L) + '\n')
    ico = write_ico(p, os.path.join(hook, 'runtime', 'loader', 'joan.ico'))
    print('image_layout.inc: %u sections; import_table.inc: %u DLLs, %u slots; joan.ico %u bytes' %
          (len(p.sections), len(imps), n, ico))


def file_mode_image(p):
    """The image joan_re.cpp's map_image builds in [Loader] Data=file (before imports), .text left zero."""
    h = header_fields(p)
    img = bytearray(h['size_of_image'])
    img[:h['size_of_headers']] = p.data[:h['size_of_headers']]
    for name, va, vs, ro, rs in p.sections:
        if name == '.text':
            continue
        raw = min(rs, vs if vs else rs)
        img[va:va + raw] = p.data[ro:ro + raw]
    return img


def check(exe, dump, imports_txt, dead_txt=None):
    p = PE(exe)
    ref = file_mode_image(p)
    got = open(dump, 'rb').read()
    ok = True
    if len(got) != len(ref):
        print('size differs: %#x vs %#x' % (len(got), len(ref)))
        return False
    # S6b: dead ranges are left out of the typed image (zero, or 0xCD when the harness poisons them)
    dead = bytearray(len(ref))
    if dead_txt:
        for ln in open(dead_txt):
            if ln.strip():
                a, n = ln.split()
                a = int(a, 16) - BASE
                dead[a:a + int(n)] = b'\1' * int(n)
    for name, va, vs, ro, rs in p.sections:
        end = va + ((vs + 0xFFF) & ~0xFFF)
        if name in CONTENT:
            diff = sum(1 for i in range(va, end) if got[i] != ref[i] and not (dead[i] and got[i] in (0, 0xCD)))
            nd = sum(dead[va:end])
            print('%-7s 0x%08x..0x%08x byte-identical to the file mode%s: %s' %
                  (name, BASE + va, BASE + end, ' outside %u dead bytes' % nd if nd else '',
                   'yes' if diff == 0 else 'NO (%u bytes differ)' % diff))
            ok &= diff == 0
        else:
            nz = sum(1 for b in got[va:end] if b)
            what = 'no code (code slots, src/runtime/code_table.cpp)' if name == '.text' else 'not embedded'
            print('%-7s 0x%08x..0x%08x %s: %s' % (name, BASE + va, BASE + end, what,
                                                 'all zero' if nz == 0 else '%u NONZERO bytes' % nz))
            ok &= nz == 0
    covered = bytearray(len(ref))
    covered[:0x1000] = b'\1' * 0x1000
    for name, va, vs, ro, rs in p.sections:
        size = (vs + 0xFFF) & ~0xFFF
        covered[va:va + size] = b'\1' * size
    stray = sum(1 for i in range(len(got)) if not covered[i] and got[i])
    print('outside headers/sections: %s' % ('all zero' if stray == 0 else '%u NONZERO bytes' % stray))
    ok &= stray == 0
    # our header: parses like joan.exe's for every field a reader may use
    h = header_fields(p)
    e = struct.unpack_from('<I', got, 0x3C)[0]
    hdr_ok = got[:2] == b'MZ' and got[e:e + 4] == b'PE\0\0'
    if hdr_ok:
        g = {}
        machine, nsec, stamp, _, _, optsz, chars = struct.unpack_from('<HHIIIHH', got, e + 4)
        names = ('magic major_linker minor_linker size_of_code size_of_init size_of_uninit entry base_of_code '
                 'base_of_data image_base section_align file_align major_os minor_os major_image minor_image '
                 'major_subsystem minor_subsystem win32_version size_of_image size_of_headers checksum subsystem '
                 'dll_characteristics stack_reserve stack_commit heap_reserve heap_commit loader_flags rva_count').split()
        g.update(zip(names, struct.unpack_from('<HBBIIIIIIIIIHHHHHHIIIIHHIIIIII', got, e + 24)))
        g.update(machine=machine, sections=nsec, timestamp=stamp, optional_size=optsz, characteristics=chars)
        diff = sorted(k for k in h if g.get(k) != h[k] and k != 'checksum')
        dirs = struct.unpack_from('<32I', got, e + 24 + 96)
        st = e + 24 + optsz
        secs = []
        for i in range(nsec):
            nm = got[st + 40 * i:st + 40 * i + 8].rstrip(b'\0').decode()
            vs, va, rs = struct.unpack_from('<III', got, st + 40 * i + 8)
            secs.append((nm, va, vs))
        hdr_ok = not diff and not any(dirs) and secs == [(n, va, vs) for n, va, vs, _, _ in p.sections]
        print('header: synthetic PE32 at e_lfanew %#x, fields equal to joan.exe (except checksum): %s, data directories '
              'empty: %s, section table equal: %s' % (e, 'yes' if not diff else 'NO ' + ','.join(diff),
                                                      'yes' if not any(dirs) else 'NO',
                                                      'yes' if secs == [(n, va, vs) for n, va, vs, _, _ in p.sections]
                                                      else 'NO'))
    else:
        print('header: NOT a PE header')
    ok &= hdr_ok
    # import table
    want = []
    for dll, funcs in imports_in_order(p):
        for slot, ordinal, name in funcs:
            want.append('%08x %s %s' % (slot, dll, ('#%u' % ordinal) if ordinal else name))
    have = open(imports_txt).read().split('\n')[:-1]
    same = have == want
    print('imports: %u slots, equal to joan.exe\'s import directory (slot, DLL, name / ordinal, order): %s' %
          (len(have), 'yes' if same else 'NO'))
    ok &= same
    print('RESULT: %s' % ('OK' if ok else 'MISMATCH'))
    return ok


if __name__ == '__main__':
    if len(sys.argv) >= 5 and sys.argv[1] == '--check':
        sys.exit(0 if check(sys.argv[2], sys.argv[3], sys.argv[4], sys.argv[5] if len(sys.argv) > 5 else None) else 1)
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    hook_dir = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src')
    generate(sys.argv[1], hook_dir)
